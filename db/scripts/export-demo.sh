#!/usr/bin/env bash
# Regenerates the mission data of the static site from the real migrations and api functions
# (throwaway database, fictional data only):
#   assets/demo/prestations.js  missions around each searchable place, mission form counters
#   assets/demo/catalog.js   places, service groups and services used by the search dialog on every page
# Usage: bash db/scripts/export-demo.sh          write the files
#        bash db/scripts/export-demo.sh --check  fail if the committed files are out of date
set -euo pipefail
cd "$(dirname "$0")/../.."
export DBMATE_MIGRATIONS_DIR=db/migrations DBMATE_NO_DUMP_SCHEMA=true

db=qdeal_demo_export
base_url=${DATABASE_URL%%\?*}
query=${DATABASE_URL#"$base_url"}

drop_db() { PGOPTIONS='-c client_min_messages=warning' psql -X -q -d postgres -c "DROP DATABASE IF EXISTS ${db} WITH (FORCE)"; }
trap drop_db EXIT
drop_db
DATABASE_URL="${base_url%/*}/${db}${query}" dbmate up >/dev/null

mapfile -t lines < <(psql -X -q -At -v ON_ERROR_STOP=1 -d "$db" -f db/fixtures/dev.sql -f db/demo/extra.sql -f db/demo/export.sql)
if [[ ${#lines[@]} -ne 2 ]]; then
  echo "db/demo/export.sql should print 2 lines, got ${#lines[@]}" >&2
  exit 1
fi
header="// Generated by db/scripts/export-demo.sh from the database functions, on fictional data. Do not edit."
declare -A files=(
  [assets/demo/prestations.js]="${header}"$'\n'"window.QDEAL_MISSIONS = ${lines[0]};"
  [assets/demo/catalog.js]="${header}"$'\n'"window.QDEAL_CATALOG = ${lines[1]};"
)

status=0
for out in "${!files[@]}"; do
  if [[ "${1:-}" == "--check" ]]; then
    if [[ ! -f "$out" || "$(cat "$out")" != "${files[$out]}" ]]; then
      echo "${out} is out of date: run bash db/scripts/export-demo.sh and commit the result." >&2
      status=1
    else
      echo "ok  ${out} est à jour"
    fi
  else
    mkdir -p "$(dirname "$out")"
    printf '%s\n' "${files[$out]}" > "$out"
    echo "${out} écrit ($(wc -c < "$out") octets)"
  fi
done
exit "$status"
