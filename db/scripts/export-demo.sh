#!/usr/bin/env bash
# Regenerates assets/demo/localisation-demo.js, the data of the static demo page, from the
# real migrations and api functions (throwaway database, fictional data only).
# Usage: bash db/scripts/export-demo.sh          write the file
#        bash db/scripts/export-demo.sh --check  fail if the committed file is out of date
set -euo pipefail
cd "$(dirname "$0")/../.."
export DBMATE_MIGRATIONS_DIR=db/migrations DBMATE_NO_DUMP_SCHEMA=true

out=assets/demo/localisation-demo.js
db=qdeal_demo_export
base_url=${DATABASE_URL%%\?*}
query=${DATABASE_URL#"$base_url"}

drop_db() { PGOPTIONS='-c client_min_messages=warning' psql -X -q -d postgres -c "DROP DATABASE IF EXISTS ${db} WITH (FORCE)"; }
trap drop_db EXIT
drop_db
DATABASE_URL="${base_url%/*}/${db}${query}" dbmate up >/dev/null

json=$(psql -X -q -At -v ON_ERROR_STOP=1 -d "$db" -f db/fixtures/dev.sql -f db/demo/extra.sql -f db/demo/export.sql)
generated=$(printf '%s\n%s\n' \
  "// Generated by db/scripts/export-demo.sh from the database functions, on fictional data. Do not edit." \
  "window.QDEAL_DEMO = ${json};")

if [[ "${1:-}" == "--check" ]]; then
  if [[ "$(cat "$out")" != "$generated" ]]; then
    echo "${out} is out of date: run bash db/scripts/export-demo.sh and commit the result." >&2
    exit 1
  fi
  echo "ok  ${out} est à jour"
else
  mkdir -p "$(dirname "$out")"
  printf '%s\n' "$generated" > "$out"
  echo "${out} écrit ($(wc -c < "$out") octets)"
fi
