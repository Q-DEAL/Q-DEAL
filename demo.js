/* Interactive location demo (demo.html / demo-fr.html).
   Data: assets/demo/localisation-demo.js, generated by db/scripts/export-demo.sh from the real
   database functions on fictional data. This file only replays two rules on top of it, both
   checked by the export: how many examples fill a provider's list, and which candidates have
   every skill a business asks for. */
(() => {
  const data = window.QDEAL_DEMO;
  const root = document.querySelector("[data-demo]");
  if (!data || !root || !window.L) return;

  const lang = document.documentElement.lang === "fr" ? "fr" : "en";
  const locale = lang === "fr" ? "fr-FR" : "en-GB";
  const plural = (n, one, many) => (n > 1 ? many : one);
  const T = {
    fr: {
      you: "Vous",
      summaryReal: (n, r) => `${n} ${plural(n, "mission", "missions")} dans votre rayon de ${r} km`,
      summaryMixed: (n, e) => `${n} ${plural(n, "mission", "missions")} dans votre zone, ${plural(n, "complétée", "complétées")} par ${e} ${plural(e, "exemple", "exemples")}`,
      summaryExamples: (e) => `Pas encore de mission réelle dans votre zone : voici ${e} ${plural(e, "exemple", "exemples")} de missions proposées sur Q DEAL`,
      badgeMission: "Mission", badgeExample: "Exemple", badgeAccepted: "Acceptée",
      approxPlace: (pc, city) => `${pc} ${city} · position à 1 km près`,
      exampleNote: "Mission d’exemple : les vraies missions de votre zone la remplaceront.",
      missingSkill: "Il vous manque une compétence demandée.",
      accept: "Accepter", decline: "Refuser",
      tomorrow: "Demain", inDays: (n) => `Dans ${n} jours`,
      approx: (km) => `≈ ${km} km`,
      announceAccepted: (title) => `Mission « ${title} » acceptée : l’adresse exacte est affichée.`,
      announceDeclined: (title) => `Mission « ${title} » refusée.`,
      count: (n) => `${n} prestataires qualifiés à moins de 10 km`,
      countHint: "Ils verront votre mission dans leur liste dès sa publication.",
      fewer: (k) => `Moins de ${k} prestataires qualifiés à moins de 10 km pour l’instant`,
      fewerHint: "Votre mission leur sera proposée dès leur inscription.",
      pickSkill: "Choisissez au moins une compétence.",
      missingTitle: "Donnez un titre à la mission.",
      published: (title, address) => `« ${title} » est publiée · ${address}`,
      waiting: "En attente des réponses des prestataires.",
      noApplicants: "Aucune réponse pour l’instant : dès qu’un prestataire qualifié accepte, son profil apparaît ici.",
      applicants: (n) => `${n} ${plural(n, "prestataire a accepté", "prestataires ont accepté")}`,
      rating: (r, n) => `★ ${r} · ${n} avis`,
      newProvider: "Nouveau sur Q DEAL",
      distanceFrom: (km) => `à ≈ ${km} km`,
    },
    en: {
      you: "You",
      summaryReal: (n, r) => `${n} ${plural(n, "task", "tasks")} within your ${r} km radius`,
      summaryMixed: (n, e) => `${n} ${plural(n, "task", "tasks")} in your area, topped up with ${e} ${plural(e, "example", "examples")}`,
      summaryExamples: (e) => `No real task in your area yet: here ${plural(e, "is", "are")} ${e} ${plural(e, "example", "examples")} of tasks posted on Q DEAL`,
      badgeMission: "Task", badgeExample: "Example", badgeAccepted: "Accepted",
      approxPlace: (pc, city) => `${pc} ${city} · location within 1 km`,
      exampleNote: "Example task: real tasks in your area will replace it.",
      missingSkill: "You are missing a required skill.",
      accept: "Accept", decline: "Decline",
      tomorrow: "Tomorrow", inDays: (n) => `In ${n} days`,
      approx: (km) => `≈ ${km} km`,
      announceAccepted: (title) => `Task “${title}” accepted: the exact address is shown.`,
      announceDeclined: (title) => `Task “${title}” declined.`,
      count: (n) => `${n} qualified providers within 10 km`,
      countHint: "They will see your task in their list as soon as it is published.",
      fewer: (k) => `Fewer than ${k} qualified providers within 10 km for now`,
      fewerHint: "Your task will be offered to them as soon as they sign up.",
      pickSkill: "Choose at least one skill.",
      missingTitle: "Give the task a title.",
      published: (title, address) => `“${title}” is published · ${address}`,
      waiting: "Waiting for providers to respond.",
      noApplicants: "No response yet: as soon as a qualified provider accepts, their profile appears here.",
      applicants: (n) => `${n} ${plural(n, "provider has accepted", "providers have accepted")}`,
      rating: (r, n) => `★ ${r} · ${n} ${plural(n, "review", "reviews")}`,
      newProvider: "New on Q DEAL",
      distanceFrom: (km) => `≈ ${km} km away`,
    },
  }[lang];

  const numberFormat = new Intl.NumberFormat(locale, { maximumFractionDigits: 1 });
  const oneDecimal = new Intl.NumberFormat(locale, { minimumFractionDigits: 1, maximumFractionDigits: 1 });
  const dateFormat = new Intl.DateTimeFormat(locale, { weekday: "long", day: "numeric", month: "long" });
  const skillLabel = new Map(data.skills.map((skill) => [skill.code, skill[lang]]));
  const css = getComputedStyle(document.documentElement);
  const colors = { orange: css.getPropertyValue("--orange").trim(), ink: css.getPropertyValue("--ink").trim(), example: "#8a8a93" };

  const el = (tag, className, text) => {
    const node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined) node.textContent = text;
    return node;
  };
  const startsLabel = (days) => {
    const date = new Date();
    date.setDate(date.getDate() + days);
    return `${days <= 1 ? T.tomorrow : T.inDays(days)} · ${dateFormat.format(date)}`;
  };
  const announce = (message) => { root.querySelector("[data-demo-live]").textContent = message; };

  /* Tabs ------------------------------------------------------------------- */
  const tabs = [...root.querySelectorAll('[role="tab"]')];
  function selectTab(tab) {
    tabs.forEach((other) => {
      const selected = other === tab;
      other.setAttribute("aria-selected", String(selected));
      other.tabIndex = selected ? 0 : -1;
      document.getElementById(other.getAttribute("aria-controls")).hidden = !selected;
    });
    if (tab.id === "tab-provider") map.invalidateSize();
  }
  tabs.forEach((tab, index) => {
    tab.addEventListener("click", () => selectTab(tab));
    tab.addEventListener("keydown", (event) => {
      if (event.key !== "ArrowRight" && event.key !== "ArrowLeft") return;
      const next = tabs[(index + (event.key === "ArrowRight" ? 1 : tabs.length - 1)) % tabs.length];
      next.focus();
      selectTab(next);
    });
  });

  /* Provider side ------------------------------------------------------------ */
  const map = L.map(root.querySelector("[data-provider-map]"), { scrollWheelZoom: false });
  map.attributionControl.setPrefix('<a href="https://leafletjs.com">Leaflet</a>');
  L.tileLayer("https://tile.openstreetmap.org/{z}/{x}/{y}.png", {
    maxZoom: 18,
    attribution: '&copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a>',
  }).addTo(map);
  const layer = L.layerGroup().addTo(map);
  const features = new Map();
  const list = root.querySelector("[data-provider-list]");
  const summary = root.querySelector("[data-provider-summary]");
  const responses = new Map();  // provider id -> Map(mission id -> "accepted" | "declined")
  let persona = data.providers[0];

  function responsesOf(provider) {
    if (!responses.has(provider.id)) {
      responses.set(provider.id, new Map(provider.missions.filter((m) => m.accepted).map((m) => [m.id, "accepted"])));
    }
    return responses.get(provider.id);
  }

  // Same order and same example top-up as api.missions_near_provider.
  function rowsOf(provider) {
    const answered = responsesOf(provider);
    const byDistance = (a, b) => a.distanceKm - b.distanceKm || a.startsInDays - b.startsInDays;
    const real = provider.missions
      .filter((m) => answered.get(m.id) !== "declined")
      .map((m) => (answered.get(m.id) === "accepted" && !m.accepted ? { ...m, ...provider.acceptedState[m.id], accepted: true } : m))
      .map((m) => ({ ...m, key: `m${m.id}` }))
      .sort(byDistance);
    const open = real.filter((m) => !m.accepted).length;
    const examples = provider.examples
      .slice(0, Math.max(0, data.config.examplesTarget - open))
      .map((e) => ({ ...e, key: `e${e.exampleId}`, isExample: true, title: lang === "fr" ? e.titleFr : e.titleEn }))
      .sort(byDistance);
    return [...real, ...examples];
  }

  function focusCard(key) {
    const card = list.querySelector(`[data-key="${key}"]`);
    if (!card) return;
    list.querySelectorAll(".is-highlighted").forEach((node) => node.classList.remove("is-highlighted"));
    card.classList.add("is-highlighted");
    card.scrollIntoView({ block: "nearest", behavior: "smooth" });
  }

  function focusFeature(key) {
    const feature = features.get(key);
    if (!feature) return;
    map.panTo(feature.getLatLng());
    feature.openTooltip();
  }

  function drawMap(rows, refit) {
    layer.clearLayers();
    features.clear();
    const home = [persona.lat, persona.lon];
    layer.addLayer(L.circle(home, { radius: persona.radiusKm * 1000, color: colors.ink, weight: 1, opacity: 0.35, dashArray: "6 6", fill: false, interactive: false }));
    rows.forEach((row) => {
      const at = [row.lat, row.lon];
      const shape = row.accepted
        ? L.circleMarker(at, { radius: 9, color: "#fff", weight: 3, fillColor: colors.orange, fillOpacity: 1 })
        : L.circle(at, row.isExample
          ? { radius: row.precisionM, color: colors.example, weight: 1.5, dashArray: "4 5", fillColor: colors.example, fillOpacity: 0.08 }
          : { radius: row.precisionM, color: colors.orange, weight: 1.5, fillColor: colors.orange, fillOpacity: 0.16 });
      shape.bindTooltip(row.isExample ? `${T.badgeExample} · ${row.title}` : row.title, { direction: "top" });
      shape.on("click", () => focusCard(row.key));
      layer.addLayer(shape);
      features.set(row.key, shape);
    });
    const you = L.circleMarker(home, { radius: 7, color: "#fff", weight: 2, fillColor: colors.ink, fillOpacity: 1 })
      .bindTooltip(T.you, { permanent: true, direction: "top", className: "demo-map-label" });
    layer.addLayer(you);
    if (refit) {
      const bounds = L.latLngBounds([home]);
      rows.forEach((row) => bounds.extend(L.latLng(row.lat, row.lon).toBounds(row.precisionM * 2)));
      if (!rows.length) bounds.extend(L.latLng(home).toBounds(4000));
      map.fitBounds(bounds, { padding: [24, 24], maxZoom: 15 });
    }
  }

  function missionCard(row) {
    const card = el("li", `demo-mission${row.isExample ? " is-example" : ""}${row.accepted ? " is-accepted" : ""}`);
    card.dataset.key = row.key;
    const head = el("div", "demo-mission-head");
    head.append(
      el("span", "demo-badge", row.isExample ? T.badgeExample : row.accepted ? T.badgeAccepted : T.badgeMission),
      el("span", "demo-distance", row.accepted ? `${oneDecimal.format(row.distanceKm)} km` : T.approx(row.distanceKm)),
    );
    const title = el("button", "demo-mission-title", row.title);
    title.type = "button";
    title.addEventListener("click", () => { focusFeature(row.key); focusCard(row.key); });
    const meta = el("p", "demo-mission-meta", [row.business, startsLabel(row.startsInDays)].filter(Boolean).join(" · "));
    const skills = el("ul", "demo-skills");
    row.skills.forEach((code) => {
      const has = persona.skills.includes(code);
      skills.append(el("li", `demo-skill${has ? " is-match" : " is-missing"}`, skillLabel.get(code)));
    });
    card.append(head, title, meta, skills);

    if (row.isExample) {
      card.append(el("p", "demo-mission-note", T.exampleNote));
      return card;
    }
    card.append(el("p", "demo-mission-place", row.accepted
      ? `${row.address}, ${row.postalCode} ${row.city}`
      : T.approxPlace(row.postalCode, row.city)));
    if (!row.accepted) {
      const actions = el("div", "demo-mission-actions");
      const accept = el("button", "button button-dark", T.accept);
      accept.type = "button";
      accept.disabled = !row.qualified;
      accept.addEventListener("click", () => respond(row, "accepted"));
      const decline = el("button", "button button-outline", T.decline);
      decline.type = "button";
      decline.addEventListener("click", () => respond(row, "declined"));
      actions.append(accept, decline);
      card.append(actions);
      if (!row.qualified) card.append(el("p", "demo-mission-note", T.missingSkill));
    }
    return card;
  }

  function renderProvider(refit) {
    const rows = rowsOf(persona);
    const real = rows.filter((row) => !row.isExample).length;
    const examples = rows.length - real;
    summary.textContent = !examples ? T.summaryReal(real, numberFormat.format(persona.radiusKm))
      : real ? T.summaryMixed(real, examples) : T.summaryExamples(examples);
    list.replaceChildren(...rows.map(missionCard));
    drawMap(rows, refit);
  }

  function respond(row, status) {
    responsesOf(persona).set(row.id, status);
    renderProvider(false);
    announce(status === "accepted" ? T.announceAccepted(row.title) : T.announceDeclined(row.title));
    if (status === "accepted") {
      focusCard(row.key);
      focusFeature(row.key);
    }
  }

  const personaChoice = root.querySelector("[data-persona-choice]");
  data.providers.forEach((provider, index) => {
    const label = el("label");
    const input = el("input");
    input.type = "radio";
    input.name = "persona";
    input.value = provider.id;
    input.checked = index === 0;
    input.addEventListener("change", () => {
      persona = provider;
      renderProvider(true);
    });
    const text = el("span", "", provider.firstName);
    text.append(el("small", "", `${lang === "fr" ? provider.areaFr : provider.areaEn} · ${provider.skills.map((code) => skillLabel.get(code)).join(", ")}`));
    label.append(input, text);
    personaChoice.append(label);
  });

  root.querySelector("[data-provider-reset]").addEventListener("click", () => {
    responses.clear();
    renderProvider(true);
  });

  /* Business side ------------------------------------------------------------ */
  const form = root.querySelector("[data-mission-form]");
  const addressSelect = form.querySelector('select[name="address"]');
  const skillBox = form.querySelector("[data-skill-choice]");
  const dateInput = form.querySelector('input[name="date"]');
  const counter = root.querySelector("[data-counter]");
  const result = root.querySelector("[data-publish-result]");
  const applicantsList = root.querySelector("[data-applicants]");
  const simulateButton = root.querySelector("[data-simulate]");
  const applicantsStatus = root.querySelector("[data-applicants-status]");
  let timers = [];

  data.business.addresses.forEach((address) => addressSelect.append(new Option(address.label, address.key)));
  data.skills.forEach((skill) => {
    const label = el("label");
    const input = el("input");
    input.type = "checkbox";
    input.name = "skills";
    input.value = skill.code;
    input.defaultChecked = skill.code === "remise_cles" || skill.code === "accueil";
    label.append(input, el("span", "", skill[lang]));
    skillBox.append(label);
  });
  const isoDate = (offset) => {
    const date = new Date();
    date.setDate(date.getDate() + offset);
    return date.toISOString().slice(0, 10);
  };
  dateInput.min = isoDate(1);

  const selectedAddress = () => data.business.addresses.find((address) => address.key === addressSelect.value);
  const selectedSkills = () => [...skillBox.querySelectorAll("input:checked")].map((input) => input.value);
  const skillMask = (codes) => data.skills.reduce((mask, skill, index) => (codes.includes(skill.code) ? mask | (1 << index) : mask), 0);

  function renderCounter() {
    const codes = selectedSkills();
    counter.classList.remove("is-low");
    if (!codes.length) {
      counter.querySelector("strong").textContent = T.pickSkill;
      counter.querySelector("span").textContent = "";
      return;
    }
    const count = selectedAddress().counts[skillMask(codes)];
    counter.classList.toggle("is-low", count === null);
    counter.querySelector("strong").textContent = count === null ? T.fewer(data.config.countDisplayMin) : T.count(count);
    counter.querySelector("span").textContent = count === null ? T.fewerHint : T.countHint;
  }

  function resetBusiness() {
    timers.forEach(clearTimeout);
    timers = [];
    form.reset();
    dateInput.value = isoDate(2);
    form.querySelectorAll("input, select, button").forEach((control) => { control.disabled = false; });
    result.hidden = true;
    applicantsList.replaceChildren();
    simulateButton.hidden = false;
    simulateButton.disabled = false;
    renderCounter();
  }

  function applicantCard(candidate, required) {
    const card = el("li", "demo-applicant");
    card.append(el("span", "demo-avatar", candidate.firstName.charAt(0)));
    const body = el("div");
    const head = el("p", "demo-applicant-head");
    head.append(el("b", "", candidate.firstName), el("span", "", T.distanceFrom(candidate.distanceKm)));
    body.append(head, el("p", "demo-applicant-rating",
      candidate.rating === null ? T.newProvider : T.rating(oneDecimal.format(candidate.rating), candidate.reviewCount)));
    const skills = el("ul", "demo-skills");
    candidate.skills.forEach((code) => skills.append(el("li", `demo-skill${required.includes(code) ? " is-match" : ""}`, skillLabel.get(code))));
    body.append(skills);
    card.append(body);
    return card;
  }

  form.addEventListener("input", renderCounter);
  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const title = form.elements.title.value.trim();
    const codes = selectedSkills();
    if (!title || !codes.length) {
      announce(!title ? T.missingTitle : T.pickSkill);
      (!title ? form.elements.title : skillBox.querySelector("input")).focus();
      return;
    }
    form.querySelectorAll("input, select, button").forEach((control) => { control.disabled = true; });
    result.hidden = false;
    result.querySelector("[data-publish-title]").textContent = T.published(title, selectedAddress().label);
    applicantsStatus.textContent = T.waiting;
    announce(T.published(title, selectedAddress().label));
    result.focus();
  });

  simulateButton.addEventListener("click", () => {
    simulateButton.disabled = true;
    const codes = selectedSkills();
    const accepted = selectedAddress().candidates.filter((candidate) => codes.every((code) => candidate.skills.includes(code)));
    if (!accepted.length) {
      applicantsStatus.textContent = T.noApplicants;
      simulateButton.hidden = true;
      return;
    }
    accepted.forEach((candidate, index) => {
      timers.push(setTimeout(() => {
        applicantsList.append(applicantCard(candidate, codes));
        applicantsStatus.textContent = T.applicants(index + 1);
        if (index === accepted.length - 1) simulateButton.hidden = true;
      }, 650 * (index + 1)));
    });
  });

  root.querySelector("[data-business-reset]").addEventListener("click", resetBusiness);

  renderProvider(true);
  resetBusiness();
})();
